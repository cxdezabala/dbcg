// One-off porting tool: evaluates the read-only prototype data files in a sandbox and
// writes their data as typed TypeScript modules (src/lib/demo/*.gen.ts) and the
// EN→ES dictionary as messages/*.json. The app never imports /reference at runtime.
import fs from 'node:fs';
import vm from 'node:vm';
import path from 'node:path';

const ref = p => fs.readFileSync(path.join('reference', p), 'utf8');
const ctx = { window: {}, console, Date, Math };
vm.createContext(ctx);
for (const f of ['synergon-data.js', 'synergon-radar.js', 'synergon-ai.js', 'synergon-i18n.js']) vm.runInContext(ref(f), ctx);
const { SYN, SYNR, SYNAI } = ctx.window;

const json = v => JSON.stringify(v, null, 1);
const header = '// GENERATED by scripts/port-reference.mjs from /reference — fictional demonstration data (Asterion Business Solutions).\n/* eslint-disable */\n';

// PACKS.framing are functions of the account name: serialise with a {account} placeholder.
const packs = {};
for (const [k, p] of Object.entries(SYN.PACKS)) packs[k] = { ...p, framing: p.framing('{account}') };
const data = { ...SYN, PACKS: packs };
let out = header + "import type * as T from './types';\n";
const typed = { ROLE_INFO: 'T.RoleInfoMap', ACCESS: 'Record<T.Role, T.View[]>', VIEW_META: 'Record<T.View, [string, string]>', ACCOUNTS: 'T.Account[]', SIGNALS: 'T.Signal[]', EXPERTS: 'T.Expert[]', KNOWLEDGE: 'T.Knowledge[]', CAPS: 'T.Cap[]', CAP_SHORT: 'string[]', TEAMS: 'T.CapTeam[]', PRIORITIES: 'T.Priority[]', THEMES: 'T.Theme[]', OPP_HYP: 'T.OppHyp[]', LEADER_RECS: 'T.LeaderRec[]', PACKS: 'Record<string, T.Pack>', LESSON: 'T.Lesson', ROLEPLAY: 'T.RolePlayTurn[]', SEED_SOLUTIONS: 'T.SeedSolution[]', COMPLETED: 'T.Completed[]', FRAMEWORKS: '[string, string][]', COMMUNITIES: '[string, number, string][]' };
for (const [k, v] of Object.entries(data)) out += `export const ${k}: ${typed[k] || 'any'} = ${json(v)} as any;\n`;
fs.writeFileSync('src/lib/demo/data.gen.ts', out);

let r = header + "import type * as T from './types';\n";
r += `export const BENCH: Record<string, T.Bench> = ${json(SYNR.BENCH)};\n`;
r += `export const LENS: Record<T.Lens, { label: string; short: string }> = ${json(SYNR.LENS)};\n`;
r += `export const COS: T.RadarCompany[] = ${json(SYNR.COS)} as any;\n`;
fs.writeFileSync('src/lib/demo/radar.gen.ts', r);

fs.writeFileSync('src/lib/demo/ai-suggest.gen.ts', header + `export const SUGGEST: Record<string, string[]> = ${json(SYNAI.SUGGEST)};\n`);

// i18n dictionary: pull the literal D object out of synergon-i18n.js
const src = ref('synergon-i18n.js');
const dStart = src.indexOf('const D={') + 'const D='.length;
const dEnd = src.indexOf('\n};', dStart) + 2;
const D = vm.runInNewContext('(' + src.slice(dStart, dEnd) + ')');
fs.writeFileSync('messages/es.json.ref', JSON.stringify(D, null, 1));
console.log('ported:', Object.keys(data).length, 'data exports;', SYNR.COS.length, 'companies;', Object.keys(D).length, 'dictionary entries');
